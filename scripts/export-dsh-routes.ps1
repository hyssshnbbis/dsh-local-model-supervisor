#requires -Version 7
<#
  export-dsh-routes.ps1 - turn supervisor/models.json into the DSH `llm-pi-ai` provider block.

  Imported models are useless inside DSH until a route points at them. Rather than making the
  user hand-write YAML for every model, this reads the SAME config the supervisor uses (through
  `supervisor.js --dump-models`, so the normalization rules live in one place) and prints the
  ready-to-paste `providers:` section.

  Every model gets a route pointing at its supervisor public port:
    managed  (path)  -> the supervisor cold-starts llama-server on demand
    external (url)   -> the supervisor forwards to the already-running server

  Examples:
    pwsh -File export-dsh-routes.ps1
    pwsh -File export-dsh-routes.ps1 -OutFile ..\dsh-routes.yml
    pwsh -File export-dsh-routes.ps1 -Config D:\other\models.json
#>
param(
    [string]$Config = '',                 # '' = <repo>\supervisor\models.json
    [string]$OutFile = '',                # '' = stdout
    [string]$ApiKeyPlaceholder = 'local-placeholder',
    [int]$MaxTokens = 8192
)

$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
if (-not $Config) { $Config = Join-Path $root 'supervisor\models.json' }
if (-not (Test-Path $Config)) { throw "config not found: $Config" }

$node = (Get-Command node -ErrorAction SilentlyContinue).Source
if (-not $node) { throw 'node.exe not found on PATH' }

$raw = & $node (Join-Path $root 'supervisor\supervisor.js') $Config --dump-models
if ($LASTEXITCODE -ne 0) { throw 'supervisor.js --dump-models failed' }
$dump = $raw | ConvertFrom-Json

$L = [System.Collections.Generic.List[string]]::new()
function Add([string]$s) { $L.Add($s) }

Add '# ============================================================================'
Add '# DSH routes for the local models declared in the supervisor config'
Add ("# generated by scripts\export-dsh-routes.ps1 from: {0}" -f (Split-Path $Config -Leaf))
Add '#'
Add '# Paste the block below into the `config.providers` of `- id: llm-pi-ai`'
Add '# in your DSH profile patch (cordis.patch.yml), then restart DSH.'
Add '# ============================================================================'
Add ''
Add '    providers:'

foreach ($m in $dump.models) {
    $base = "http://127.0.0.1:$($m.publicPort)/v1"
    $kind = if ($m.external) { 'external server (forwarded; not started or stopped by the supervisor)' }
            else { "managed: cold-started on demand, released after $($dump.idleTimeoutSec)s idle" }
    Add ("      # {0} — {1}" -f $kind, $m.label)
    if ($m.external) {
        Add ("      # upstream: {0}" -f $m.url)
    } elseif ($m.softContextLimit) {
        Add ("      # soft context ceiling: {0} tokens (real {1})" -f $m.softContextLimit, $m.ctxSize)
    }
    Add ("      {0}:" -f $m.key)
    Add ("        displayName: {0}" -f $m.label)
    Add  '        api: openai-completions'
    Add ("        baseURL: {0}" -f $base)
    Add  '        headers:'
    Add ("          Authorization: Bearer {0}" -f $ApiKeyPlaceholder)
    Add  '        compat:'
    Add  '          thinkingFormat: deepseek'
    Add  '        models:'
    Add ("          - id: {0}" -f $m.alias)
    Add ("            name: {0}" -f $m.label)
    if ($m.ctxSize) {
        Add ("            contextWindow: {0}" -f $m.ctxSize)
    } else {
        Add  '            contextWindow: 32768   # TODO: set this server''s real context window'
    }
    Add ("            maxTokens: {0}" -f $MaxTokens)
    Add  '            reasoningEfforts:'
    Add  '              "off":'
    Add  '              low: low'
    Add  '              medium: medium'
    Add  '              high: xhigh'
    Add ''
}

$text = ($L -join [Environment]::NewLine) + [Environment]::NewLine

if ($OutFile) {
    $OutFile = [IO.Path]::GetFullPath($OutFile)
    [IO.File]::WriteAllText($OutFile, $text, [Text.UTF8Encoding]::new($false))
    Write-Host ("wrote {0} routes to {1}" -f $dump.models.Count, $OutFile) -ForegroundColor Green
} else {
    Write-Output $text
}
